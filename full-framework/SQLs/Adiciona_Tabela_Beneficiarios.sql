/* Adiciona a tabela de Beneficiários */
CREATE TABLE dbo.BENEFICIARIOS
(
    ID        BIGINT IDENTITY(1,1) NOT NULL PRIMARY KEY,
    CPF       CHAR(11)    NOT NULL,
    NOME      VARCHAR(50) NOT NULL,
    IDCLIENTE BIGINT      NOT NULL FOREIGN KEY REFERENCES dbo.CLIENTES (ID) ON DELETE NO ACTION,
    CONSTRAINT UQ_BENEFICIARIOS_CLIENTE_CPF UNIQUE (IDCLIENTE, CPF)
);